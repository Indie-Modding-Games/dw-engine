/** "es" for a Spanish locale or setting, otherwise "en". */
export function pickLanguage(setting, locale) {
  for (const value of [setting, locale]) {
    if (typeof value === 'string' && value.trim()) return value.trim().toLowerCase().startsWith('es') ? 'es' : 'en'
  }
  return 'en'
}

/** The text in `language`, with {name} replaced by values.name. */
export function translate(language, text, values = {}) {
  const template = language === 'es' ? ES[text] ?? text : text
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in values ? String(values[name]) : match))
}
